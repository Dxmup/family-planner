-- Reading log: a book cache plus one row per (child, book) on a child's shelf.
--
--   books        isbn (13-digit, primary key), title, author, cover_url, pages.
--                A cache of looked-up book details, written when a parent saves.
--   reading_log  one row per child per book: reading -> finished, with the
--                library due/returned dates and the points the book is worth.
--
-- Access (same conventions as 20261123000000_require_auth_for_reads.sql):
--   * SELECT on both tables  -> any signed-in account ("authenticated read").
--   * INSERT/UPDATE/DELETE   -> parents only, gated by public.is_parent().
--   * Extra, mirroring the chore-completion taps: any signed-in account may
--     UPDATE reading_log so the wall tablet (a non-parent account) can mark a
--     book finished. A trigger narrows that to exactly one transition for
--     non-parents: status 'reading' -> 'finished' (setting finished_on).
--     Nothing else on the row (points, child, book, due date, undoing a
--     finish, marking returned) can be changed without a parent login.
--     The trigger lets through sessions with no JWT (SQL editor, service role).
--
-- Finished books count toward a child's star balance: the API adds
-- reading_log.points (status = 'finished') to the totals it computes, so no
-- bonus_points rows are written by non-parents.
--
-- Assumes members.id is a whole number (the API treats it as Number(id)); the
-- foreign key uses bigint, which is compatible with integer or bigint ids.
--
-- Idempotent: safe to run more than once.
-- Rollback: see the bottom of this file.

begin;

-- 1. Tables ------------------------------------------------------------------

create table if not exists public.books (
  isbn        text primary key check (isbn ~ '^97[89][0-9]{10}$'),
  title       text not null check (length(btrim(title)) > 0),
  author      text,
  cover_url   text,
  pages       integer check (pages is null or pages > 0),
  created_at  timestamptz not null default now()
);

create table if not exists public.reading_log (
  id          bigint generated by default as identity primary key,
  member_id   bigint not null references public.members(id) on delete cascade,
  isbn        text   not null references public.books(isbn),
  source      text   not null default 'owned' check (source in ('library', 'owned')),
  status      text   not null default 'reading' check (status in ('reading', 'finished')),
  due_date    date,
  returned_on date,
  finished_on date,
  points      integer not null default 5 check (points >= 0 and points <= 100),
  created_at  timestamptz not null default now()
);

create index if not exists reading_log_member_idx on public.reading_log (member_id);
create index if not exists reading_log_isbn_idx   on public.reading_log (isbn);

-- A child can have a given book on the shelf as "reading" only once at a time
-- (they can read it again after finishing it).
create unique index if not exists reading_log_one_active_idx
  on public.reading_log (member_id, isbn) where status = 'reading';

-- 2. Row-level security ------------------------------------------------------

alter table public.books       enable row level security;
alter table public.reading_log enable row level security;

drop policy if exists "authenticated read" on public.books;
create policy "authenticated read" on public.books
  for select to authenticated using (true);

drop policy if exists "parents insert" on public.books;
create policy "parents insert" on public.books
  for insert to authenticated with check (public.is_parent());
drop policy if exists "parents update" on public.books;
create policy "parents update" on public.books
  for update to authenticated using (public.is_parent()) with check (public.is_parent());
drop policy if exists "parents delete" on public.books;
create policy "parents delete" on public.books
  for delete to authenticated using (public.is_parent());

drop policy if exists "authenticated read" on public.reading_log;
create policy "authenticated read" on public.reading_log
  for select to authenticated using (true);

drop policy if exists "parents insert" on public.reading_log;
create policy "parents insert" on public.reading_log
  for insert to authenticated with check (public.is_parent());
drop policy if exists "parents update" on public.reading_log;
create policy "parents update" on public.reading_log
  for update to authenticated using (public.is_parent()) with check (public.is_parent());
drop policy if exists "parents delete" on public.reading_log;
create policy "parents delete" on public.reading_log
  for delete to authenticated using (public.is_parent());

-- Any signed-in account (the tablet) may update; the trigger below limits what.
drop policy if exists "authenticated update" on public.reading_log;
create policy "authenticated update" on public.reading_log
  for update to authenticated using (true) with check (true);

-- 3. Narrow what a non-parent update may do ----------------------------------

create or replace function public.reading_log_guard_update()
returns trigger
language plpgsql
as $$
begin
  -- No JWT (SQL editor, service role, migrations): not an app user, let it through.
  if auth.uid() is null or public.is_parent() then
    return new;
  end if;
  -- Non-parents: only reading -> finished, changing nothing but status/finished_on.
  if old.status = 'reading' and new.status = 'finished'
     and new.id          = old.id
     and new.member_id   = old.member_id
     and new.isbn        = old.isbn
     and new.source      = old.source
     and new.due_date    is not distinct from old.due_date
     and new.returned_on is not distinct from old.returned_on
     and new.points      = old.points
     and new.created_at  = old.created_at then
    return new;
  end if;
  raise exception 'Parent login required' using errcode = '42501';
end;
$$;

drop trigger if exists reading_log_guard_update on public.reading_log;
create trigger reading_log_guard_update
  before update on public.reading_log
  for each row execute function public.reading_log_guard_update();

-- 4. Privileges --------------------------------------------------------------

revoke all on public.books, public.reading_log from anon;
grant select, insert, update, delete on public.books, public.reading_log to authenticated;

commit;

